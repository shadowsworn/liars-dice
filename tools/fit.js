/* Turns self-play records into solver parameters and writes js/params.js.
 *
 *   node tools/fit.js <previous params.json | -> <out params.json> <selfplay-*.json ...>
 *
 *   open      per table size, the threshold and steepness that best predict when bots open
 *             (maximum likelihood over a grid)
 *   leftover  per table size and bid height, how often a bidder still drank after being raised,
 *             shrunk toward the previous value when there is little data
 *   beta, lambda  how strongly bids reveal hands, by maximum likelihood over the recorded bids
 */
'use strict';
const fs = require('fs');
const path = require('path');
global.window = global;
for (const f of ['rules', 'solver']) require(path.join(__dirname, '..', 'js', f + '.js'));
const { Rules: R, Solver: S } = global.LD;

const [prevFile, outFile, ...files] = process.argv.slice(2);
const prev = prevFile && prevFile !== '-' ? JSON.parse(fs.readFileSync(prevFile, 'utf8')) : { open: {}, leftover: {} };
const runs = files.map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
// reads (per table size overrides, e.g. 1 on 1) are chosen by head-to-head tests, not fitted, so carry them over.
const out = { beta: prev.beta || 1.1, lambda: prev.lambda || 0.25, reads: prev.reads || {}, open: {}, leftover: {}, meta: { rounds: {} } };

// --- when does the next player open?
for (const run of runs) {
  const { n, open } = run;
  out.meta.rounds[n] = run.rounds;
  let best = null;
  for (let tau = 0.1; tau <= 0.7001; tau += 0.01) {
    for (const slope of [4, 6, 8, 10, 12, 15, 20, 25, 30, 40, 60]) {
      let ll = 0;
      open.forEach(([tot, yes], bin) => {
        if (!tot) return;
        const o = Math.min(1 - 1e-6, Math.max(1e-6, 1 / (1 + Math.exp(slope * (bin / 50 - tau)))));
        ll += yes * Math.log(o) + (tot - yes) * Math.log(1 - o);
      });
      if (!best || ll > best.ll) best = { ll, tau: +tau.toFixed(2), slope };
    }
  }
  out.open[n] = { tau: best.tau, slope: best.slope };
}

// --- leftover risk after being raised
const priorL = (n) => (n === 2 ? 0.45 : 0.05 + 0.35 / (n - 1));
for (const run of runs) {
  const { n, leftover } = run;
  const before = prev.leftover[n] || leftover.map(() => priorL(n));
  out.leftover[n] = leftover.map(([tot, lost], i) => +((lost + 30 * before[i]) / (tot + 30)).toFixed(3));
}

// --- how much bids reveal
const NH = 7776;
const NK = R.KEYS.length;
const COUNTS = R.KEYS.map((k) => S.HANDS.map((h) => R.countHand(h, k.face, k.zai, R.DEFAULT_RULES)));
const MEANS = COUNTS.map((a) => a.reduce((s, x) => s + x, 0) / NH);
const reads = runs.flatMap((r) => r.reads);
let bestRead = null;
for (let beta = 0.3; beta <= 2.5001; beta += 0.1) {
  // softmax part per hand depends only on beta
  const soft = new Map();
  const softFor = (h) => {
    if (soft.has(h)) return soft.get(h);
    const e = R.KEYS.map((_, k) => Math.exp(beta * (COUNTS[k][h] - MEANS[k])));
    const z = e.reduce((s, x) => s + x, 0);
    const v = e.map((x) => x / z);
    soft.set(h, v);
    return v;
  };
  for (let lambda = 0.05; lambda <= 0.9501; lambda += 0.05) {
    let ll = 0;
    for (const [h, k] of reads) ll += Math.log((1 - lambda) * softFor(h)[k] + lambda / NK);
    if (!bestRead || ll > bestRead.ll) bestRead = { ll, beta: +beta.toFixed(1), lambda: +lambda.toFixed(2) };
  }
}
out.beta = bestRead.beta;
out.lambda = bestRead.lambda;
out.meta.readSamples = reads.length;

fs.writeFileSync(outFile, JSON.stringify(out, null, 2));
const js = `/* Generated by tools/fit.js from self-play (${Object.entries(out.meta.rounds).map(([n, r]) => `${r} rounds × ${n} players`).join(', ')}).
 * Do not edit by hand: rerun tools/calibrate.sh. */
window.LD = window.LD || {};
window.LD.PARAMS = ${JSON.stringify({ beta: out.beta, lambda: out.lambda, reads: out.reads, open: out.open, leftover: out.leftover }, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'params.js'), js);
console.log(JSON.stringify({ beta: out.beta, lambda: out.lambda, open: out.open, leftover: out.leftover }));
